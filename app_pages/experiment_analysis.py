# ============================================================================================ 7. Power
st.header("7 · Sample size from pilot effects and dependence", divider="gray")
st.caption("Effect sizes and variance components (participant, path, residual) are estimated from the data above as "
           "a pilot. Datasets are simulated with the allocation schedule and the same estimators; power is the share "
           "whose 95% interval excludes zero.")
c1, c2, c3 = st.columns(3)
reps = c1.select_slider("Simulated datasets per size", [50, 100, 200, 500], 100, key="exa_reps")
target = c2.select_slider("Target power", [0.8, 0.9], 0.8, key="exa_target")
grid = c3.multiselect("Sample sizes", [16, 32, 48, 64, 96, 128, 192, 256, 384, 512],
                      [16, 32, 64, 128, 256], key="exa_grid")


@st.cache_data(show_spinner=False, max_entries=4)
def _power(key, summ, reps, grid):
    comps = [HA.pilot_components(summ, o) for o in HA.OUTCOMES]
    pw = pd.concat([HA.power_analysis(c, tuple(sorted(grid)), int(reps)) for c in comps], ignore_index=True)
    return comps, pw


pilot_label = ("SYNTHETIC pilot (simulated participants; assumed effects)" if synthetic
               else f"human pilot data ({len(keep)} participants)")
if st.button("Run the power analysis", key="exa_power", disabled=not grid):
    st.session_state["exa_power_key"] = (key, reps, tuple(grid))
comps, pw = None, None
if st.session_state.get("exa_power_key") == (key, reps, tuple(grid)):
    with st.spinner("Simulating datasets…"):
        comps, pw = _power(key, summ, reps, tuple(grid))
    st.dataframe(pd.DataFrame(comps).round(4), hide_index=True, width="stretch")
    rq = HA.required_n(pw, target)
    st.dataframe(rq, hide_index=True, width="stretch")
    o = st.selectbox("Outcome", list(HA.OUTCOMES), format_func=HA.OUTCOMES.get, key="exa_pw_out")
    f = go.Figure()
    for j, (e, g) in enumerate(pw[pw["outcome"] == o].groupby("effect", sort=False)):
        f.add_trace(go.Scatter(x=g["n"], y=g["power"], mode="lines+markers", name=e, line=dict(color=CAT[j])))
    f.add_hline(y=target, line=dict(color="gray", dash="dot"))
    f.update_xaxes(title="Participants")
    f.update_yaxes(title="Power", range=[0, 1])
    st.plotly_chart(style(f, 320))
    if synthetic:
        st.warning("These sample sizes come from a synthetic pilot with assumed effects: they check the design; "
                   "recompute them from a human pilot before the main study.", icon="🧪")
    download(pw, "power_analysis.csv", "Download power results (CSV)")

st.download_button("Prospective analysis plan (Markdown)",
                   HA.analysis_plan(PLAN, comps, pw, pilot_label if comps else "", EXPERIMENT_PLAN).encode(),
                   file_name=f"analysis_plan_{PLAN.digest}.md", mime="text/markdown", type="primary",
                   help="Includes the sample-size section once the power analysis has been run.")

