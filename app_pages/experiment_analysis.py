# ============================================================================================ 3. Treatment effects
st.header("3 · Treatment effects (randomized)", divider="gray")
st.caption("Within participants: each condition against the baseline, with participant, path and position fixed "
           "effects and intervals clustered by participant (by session when recorded). Between participants: "
           "randomized aid and elicitation. " + ("Synthetic pilot: these numbers describe the simulated design only."
                                                if synthetic else ""))
tabs = st.tabs([HA.OUTCOMES[o] for o in HA.OUTCOMES])
all_w, all_b = [], []
for t, o in zip(tabs, HA.OUTCOMES):
    with t:
        w = HA.within_effects(summ, o)
        b = HA.between_effects(summ, o)
        all_w.append(w)
        all_b.append(b)
        if len(w):
            f = go.Figure(go.Scatter(x=w["effect"], y=[f"{r} ({m})" for r, m in zip(w["contrast"], w["mechanism"])],
                                     mode="markers", marker=dict(size=10, color=CAT[0]),
                                     error_x=dict(type="data", symmetric=False, array=w["hi"] - w["effect"],
                                                  arrayminus=w["effect"] - w["lo"])))
            f.add_vline(x=0, line=dict(color="gray", dash="dot"))
            st.plotly_chart(style(f, 220, title="Condition contrasts with 95% intervals"))
            st.dataframe(w.round(4), hide_index=True, width="stretch")
        if len(b):
            st.dataframe(b.round(4), hide_index=True, width="stretch")
eff = pd.concat(all_w + all_b, ignore_index=True)
download(eff, "experiment_treatment_effects.csv", "Download treatment effects (CSV)")

# ============================================================================================ 4. Mechanisms
st.header("4 · Mechanism models", divider="gray")
st.caption("Adjustment probability and adjustment magnitude are modeled separately (hurdle models), with lapse, "
           "inertia, rounding, aid following and partially pooled individual parameters. Models are compared on "
           "held-out blocks (leave one block out per participant).")


@st.cache_data(show_spinner=False, max_entries=4)
def _mechanisms(key, df):
    data = HM.prepare(df)
    comp, fits, per = HM.compare_models(data)
    return comp, fits["full"].params, HA.mechanism_effects(fits["full"])


if st.button("Fit and compare the mechanism models", key="exa_mech"):
    st.session_state["exa_mech_key"] = key
if st.session_state.get("exa_mech_key") == key:
    with st.spinner("Fitting four models with held-out blocks…"):
        comp, params, mech = _mechanisms(key, df)
    st.markdown("**Held-out prediction** (higher log score is better; lower Brier score and RMSE are better)")
    st.dataframe(comp.round(4), hide_index=True, width="stretch")
    st.markdown("**Population parameters of the inertia + rounding model** (condition shifts on the logit of "
                "adjustment probability; participant-bootstrap intervals; interpret only parameters that the recovery "
                "check below recovers)")
    st.dataframe(mech.round(4), hide_index=True, width="stretch")
    download(params, "experiment_individual_parameters.csv", "Download individual parameters (CSV)")

# ============================================================================================ 5. Recovery
st.header("5 · Parameter and model recovery (synthetic)", divider="gray")
st.caption("Synthetic participants with known parameters and models are run through the same market and fitted with "
           "the same code. A parameter that is not recovered, or models that are confused, should not be interpreted "
           "in human data.")
c1, c2 = st.columns(2)
pr_n = c1.slider("Synthetic participants (parameter recovery)", 16, 64, 24, 8, key="exa_pr_n")
mr_n = c2.slider("Synthetic participants per model (model recovery)", 4, 24, 6, 2, key="exa_mr_n")


@st.cache_data(show_spinner=False, max_entries=2)
def _recovery(pr_n, mr_n):
    pr, _ = HM.parameter_recovery(int(pr_n), seed=11)
    conf, per = HM.model_recovery(int(mr_n), seed=12)
    return pr, conf, per


if st.button("Run recovery checks", key="exa_rec"):
    st.session_state["exa_rec_key"] = (pr_n, mr_n)
if st.session_state.get("exa_rec_key") == (pr_n, mr_n):
    with st.spinner("Simulating and fitting…"):
        pr, conf, per = _recovery(pr_n, mr_n)
    c1, c2 = st.columns(2)
    c1.markdown("**Parameter recovery**")
    c1.dataframe(pr.round(3), hide_index=True, width="stretch")
    f = go.Figure(go.Heatmap(z=conf.to_numpy(), x=[HM.MODEL_LABELS[m] for m in conf.columns],
                             y=[HM.MODEL_LABELS[m] for m in conf.index], colorscale="Blues", zmin=0, zmax=1,
                             text=np.round(conf.to_numpy(), 2), texttemplate="%{text}"))
    f.update_xaxes(title="Selected (best held-out log score)")
    f.update_yaxes(title="Generating model")
    c2.plotly_chart(style(f, 340, title="Model-confusion matrix"))
    download(conf.reset_index().rename(columns={"generating": "generating_model"}), "model_confusion_matrix.csv",
             "Download the model-confusion matrix (CSV)")
    download(pr, "parameter_recovery.csv", "Download parameter recovery (CSV)")

