@dataclass(frozen=True)
class InventoryPlan:
    periods: int = 1000
    burn_in: int = 100
    n_train: int = 10
    n_val: int = 10
    n_test: int = 20
    budgets: Tuple[int, ...] = (1, 2, 4, 8, 16)
    reps: int = 3
    seed: int = 4242
    grid_step: float = 1.0
    families: Tuple[str, ...] = tuple(FAMILIES)

    def env_sets(self) -> Dict[str, List[TaskEnv]]:
        sets = {name: tasks._env_set("inventory", n, self.seed * 10 + i)
                for i, (name, n) in enumerate((("train", self.n_train), ("validation", self.n_val),
                                               ("test", self.n_test)), 1)}
        seeds = [{e.seed for e in v} for v in sets.values()]
        assert not (seeds[0] & seeds[1] or seeds[0] & seeds[2] or seeds[1] & seeds[2]), "environment sets overlap"
        return sets

    def to_dict(self) -> Dict:
        return asdict(self)


QUICK_INVENTORY = dict(periods=400, burn_in=50, n_train=3, n_val=3, n_test=5, budgets=(1, 2, 4), reps=2)


def run_inventory(plan: InventoryPlan, progress=None) -> Dict:
    sets = plan.env_sets()
    results: Dict[str, Tuned] = {}
    for j, key in enumerate(plan.families):
        fam = FAMILIES[key]
        if progress:
            progress(j / len(plan.families), fam.name)
        run = lambda env, cfg, key=key: run_agent(env, key, cfg, plan.periods, plan.burn_in, plan.grid_step)
        results[key] = tune(fam, run, sets["train"], sets["validation"], sets["test"], plan.budgets, plan.reps,
                            plan.seed + 101 * j)
    if progress:
        progress(1.0, "Done")
    return dict(results=results, ranking=ranking(results, FAMILIES, baseline="rule_b"),
                curve=budget_curve(results), plan=plan.to_dict(),
                environments={k: [asdict(e) for e in v] for k, v in sets.items()})
