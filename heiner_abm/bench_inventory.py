"""Decision benchmarks in the inventory task: Bayesian learning with change detection (A) and distributionally robust
optimization (B), compared with the task's existing rules under the tuning protocol of heiner_abm.bench_tuning.

Environment (unchanged; generated by heiner_abm.tasks._streams, which belongs to a frozen plan and is only imported)
    Newsvendor with shifting demand (Arrow, Harris & Marschak 1951). The mean demand mu_t starts at MU0 = 100 and in
    each period, with probability equal to the environment's hazard h, jumps by N(0, JUMP_SD^2) and is clipped to
    [MU_LO, MU_HI] = [30, 170]. Demand d_t = max(0, mu_t + sigma e_t); the agent observes y_t = d_t + tau u_t (e, u
    standard normal). Ordering S costs H_OVER per unit left over and P_SHORT per unit short, so with a known demand
    distribution the optimal order is its critical fractile p / (p + h) = 0.8 (Arrow, Harris & Marschak 1951). The
    order for period t uses observations up to t - 1.

Agents
    rule_b        the task's default rule: slow exponentially weighted forecast plus a fractile margin (no tuning).
    ewma          the task's flexible rule with a tuned smoothing gain.
    saa           sample average approximation (empirical stochastic optimization) over the last N observations:
                  minimize the average newsvendor loss, i.e. order the ceil(0.8 N)-th smallest observation.
    dro           distributionally robust newsvendor over the last N observations. Ambiguity set: every
                  distribution q on the N observed values with modified chi-squared distance
                  sum_i (q_i - 1/N)^2 / (1/N) <= rho to the empirical distribution (Ben-Tal et al. 2013). The order
                  minimizes the worst-case expected loss over the set (solved exactly for each order quantity, then a
                  golden-section search over the order quantity, whose worst-case loss is convex). rho = 0 is SAA.
                  N and rho are calibrated on the training environments only.
    bocpd         Bayesian online change-point detection (Adams & MacKay 2007; exact recursion as in Fearnhead &
                  Liu 2007): segments with a constant hazard H, a normal prior N(m0, s0^2) on each segment's mean,
                  observations N(mean, sm^2). MISSPECIFIED on purpose: new segment means are drawn afresh from the
                  prior instead of jumping from the previous level, and clipping, censoring at zero and the split
                  between demand and observation noise are ignored. H, s0 and sm are tuned on training environments;
                  m0 = MU0. Orders the 0.8-quantile of its posterior predictive (posterior expected utility).
    bayes_true    BENCHMARK, correctly specified: an exact Bayesian filter of the generating process above on a grid of
                  mean demands (step `grid_step`), with the environment's true hazard, sigma and tau. Orders the
                  0.8-quantile of the posterior predictive demand max(0, mu + sigma e), which maximizes posterior
                  expected payoff (demand is observed whatever is ordered, so acting does not change information and
                  the myopic Bayes decision is optimal). It knows the generating parameters, so it is reported beside
                  the ranking, not in it. It is exact for the grid version of the process; the grid step is an
                  approximation of the continuous jumps (checked by refining the grid).
    oracle        ORACLE: knows mu_t and orders max(0, mu_t + 0.8-quantile of sigma e). Not ranked.
"""
