MU0, MU_LO, MU_HI, JUMP_SD = 100.0, 30.0, 170.0, 30.0           # constants of tasks._streams (inventory)
FRACTILE = P_SHORT / (P_SHORT + H_OVER)                          # 0.8
Z_FRAC = float(ndtri(FRACTILE))


def _phi(x):
    return np.exp(-0.5 * x * x) / np.sqrt(2.0 * np.pi)


# ================================================================================================ A. Bayes, correct model
def grid_transition(grid: np.ndarray, hazard: float, jump_sd: float = JUMP_SD) -> np.ndarray:
    """P[i, j] = probability that the mean moves from grid[i] to grid[j] in one period: it stays with probability
    1 - hazard; otherwise it jumps by N(0, jump_sd^2) and is clipped to the grid's range (mass beyond an end goes to
    that end, as the clipping in tasks._streams does)."""
    mid = (grid[1:] + grid[:-1]) / 2.0
    upper = np.append(mid, np.inf)
    lower = np.insert(mid, 0, -np.inf)
    K = ndtr((upper[None, :] - grid[:, None]) / jump_sd) - ndtr((lower[None, :] - grid[:, None]) / jump_sd)
    return (1.0 - hazard) * np.eye(len(grid)) + hazard * K


def obs_likelihood(y: float, mu: np.ndarray, sigma: float, tau: float) -> np.ndarray:
    """Density of the observation y given mean demand mu: y = max(0, mu + sigma e) + tau u."""
    if tau <= 0:
        return ndtr(-mu / sigma) if y <= 0 else _phi((y - mu) / sigma) / sigma
    s = np.sqrt(sigma ** 2 + tau ** 2)
    m_post = (mu * tau ** 2 + y * sigma ** 2) / s ** 2
    s_post = sigma * tau / s
    return ndtr(-mu / sigma) * _phi(y / tau) / tau + _phi((y - mu) / s) / s * ndtr(m_post / s_post)


def censored_mixture_quantile(w: np.ndarray, mu: np.ndarray, sigma: float, frac: float = FRACTILE,
                              iters: int = 60) -> float:
    """Smallest S >= 0 with P(max(0, M + sigma e) <= S) >= frac, M ~ sum_j w_j delta(mu_j): the order maximizing
    expected payoff under that predictive (Arrow, Harris & Marschak 1951)."""
    cdf = lambda S: float(np.dot(w, ndtr((S - mu) / sigma)))
    if cdf(0.0) >= frac:
        return 0.0
    lo, hi = 0.0, float(mu.max() + 10 * sigma)
    for _ in range(iters):
        mid = 0.5 * (lo + hi)
        lo, hi = (mid, hi) if cdf(mid) < frac else (lo, mid)
    return hi


def bayes_true_orders(y: np.ndarray, hazard: float, sigma: float, tau: float, grid_step: float = 1.0,
                      return_post: bool = False):
    """Orders of the correctly specified Bayesian filter (see the module docstring) for observations y."""
    grid = np.arange(MU_LO, MU_HI + 1e-9, grid_step)
    P = grid_transition(grid, hazard)
    w = np.zeros(len(grid))
    w[np.argmin(np.abs(grid - MU0))] = 1.0                       # mu before period 0 is MU0
    S = np.empty(len(y))
    means = np.empty(len(y))
    for t in range(len(y)):
        pred = w @ P                                             # mean demand of period t, before y_t is seen
        S[t] = censored_mixture_quantile(pred, grid, sigma)
        post = pred * obs_likelihood(y[t], grid, sigma, tau)
        w = post / post.sum()
        means[t] = float(w @ grid)
    return (S, means) if return_post else S


def filter_posterior(y: np.ndarray, grid: np.ndarray, P: np.ndarray, w0: np.ndarray, lik) -> np.ndarray:
    """Generic forward filter on a finite state space (used to check bayes_true_orders against enumeration)."""
    w = w0.copy()
    for t in range(len(y)):
        pred = w @ P
        post = pred * lik(y[t], grid)
        w = post / post.sum()
    return w


# ================================================================================================ A. BOCPD, misspecified
class BOCPD:
    """Bayesian online change-point detection with a Gaussian segment model of known variance (Adams & MacKay 2007).

    Convention: a change at t means y_t starts a new segment; run length r_t counts the periods of the current
    segment including t. Segment means ~ N(m0, s0^2) independently; y | mean ~ N(mean, sm^2); P(change) = hazard each
    period. Run lengths above `rmax` are merged into the longest kept one (an approximation; tests use rmax >= T).

    Calendar time and observation are separate. `self.w` always holds the run-length posterior after the last period
    the model has been told about. Exactly one hazard transition belongs to each period:
        update(y)       a period whose demand was observed: hazard transition, then condition on y;
        advance()       a period whose demand was not observed: the hazard transition alone, marginalizing over the
                        unseen y, so a change can still have happened and the segment posteriors of continuing runs
                        are carried forward unchanged;
        predictive()    the mixture for the *next* period: it applies that period's hazard transition to the stored
                        posterior without mutating it.
    Calling advance() for a missing period and then predictive() therefore applies one transition per period and no
    more. Skipping advance() (the behavior before 8 October 2026) froze the run-length posterior whenever a demand
    was unobserved, so regime uncertainty stopped accumulating across gaps in the data."""

    def __init__(self, hazard: float, m0: float, s0: float, sm: float, rmax: int = 300):
        self.H, self.m0, self.v0, self.v = hazard, m0, s0 ** 2, sm ** 2
        self.rmax = rmax
        self.w = np.zeros(0)            # P(r_t = r | y_1..t) for r = 1 .. len(w)
        self.mu = np.zeros(0)           # posterior mean of the segment mean, per run length
        self.var = np.zeros(0)

    def predictive(self) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        """Mixture (weights, means, variances) predicting the next observation."""
        if len(self.w) == 0:
            return np.ones(1), np.array([self.m0]), np.array([self.v0 + self.v])
        wts = np.append((1 - self.H) * self.w, self.H)
        return wts, np.append(self.mu, self.m0), np.append(self.var, self.v0) + self.v

    def advance(self):
        """A period with no observation: apply the hazard transition only (no conditioning).

        A new run starts with probability H and reverts to the segment-mean prior; continuing runs keep their
        posterior means and variances, because nothing was observed to update them. Before the first observation
        there is no posterior to propagate and this is a no-op."""
        if len(self.w) == 0:
            return
        self.w = np.append(self.H, (1 - self.H) * self.w)
        self.mu = np.append(self.m0, self.mu)
        self.var = np.append(self.v0, self.var)
        self._truncate()

    def _truncate(self):
        if len(self.w) > self.rmax:                              # merge the tail into the longest kept run length
            self.w[self.rmax - 1] += self.w[self.rmax:].sum()
            self.w, self.mu, self.var = self.w[:self.rmax], self.mu[:self.rmax], self.var[:self.rmax]

    def update(self, y: float):
        wts, m, s2 = self.predictive()
        lik = _phi((y - m) / np.sqrt(s2)) / np.sqrt(s2)
        joint = wts * lik
        if len(self.w) == 0:
            new_w, cont = joint, np.zeros(0)
        else:
            cont = joint[:-1]                                    # runs that continue: r -> r + 1
            new_w = np.append(joint[-1], cont)                   # r = 1 first
        prec_new = 1 / self.v0 + 1 / self.v
        mu_new = (self.m0 / self.v0 + y / self.v) / prec_new
        prec = 1 / self.var + 1 / self.v
        mu_c = (self.mu / self.var + y / self.v) / prec
        self.mu = np.append(mu_new, mu_c)
        self.var = np.append(1 / prec_new, 1 / prec)
        self.w = new_w / new_w.sum()
        self._truncate()


def gaussian_mixture_quantile(w, m, s2, frac: float = FRACTILE, iters: int = 60) -> float:
    s = np.sqrt(s2)
    cdf = lambda x: float(np.dot(w, ndtr((x - m) / s)))
    lo, hi = float((m - 10 * s).min()), float((m + 10 * s).max())
    for _ in range(iters):
        mid = 0.5 * (lo + hi)
        lo, hi = (mid, hi) if cdf(mid) < frac else (lo, mid)
    return hi


def bocpd_orders(y: np.ndarray, hazard: float, s0: float, sm: float, m0: float = MU0, rmax: int = 300) -> np.ndarray:
    """Orders from the posterior predictive, one per period. A period whose demand is NaN (unobserved) advances
    calendar time by its hazard transition without conditioning, so regime uncertainty keeps accumulating."""
    model = BOCPD(hazard, m0, s0, sm, rmax)
    S = np.empty(len(y))
    for t in range(len(y)):
        S[t] = max(0.0, gaussian_mixture_quantile(*model.predictive()))
        if np.isnan(y[t]):
            model.advance()
        else:
            model.update(float(y[t]))
    return S


# ================================================================================================ B. SAA and DRO
def newsvendor_loss(S, d):
    return H_OVER * np.maximum(S - d, 0.0) + P_SHORT * np.maximum(d - S, 0.0)


def chi2_worst_case(L: np.ndarray, rho) -> np.ndarray:
    """max_q sum_i q_i L_i over distributions q on the N atoms with sum_i (q_i - 1/N)^2 / (1/N) <= rho (modified
    chi-squared distance to the empirical distribution; Ben-Tal et al. 2013). Exact, along the last axis.

    KKT: the maximizer puts q_i = 1/k + c (L_i - mean of the top k) on the k largest losses and 0 elsewhere, either on
    the boundary of the ball (c > 0) or, if the ball is not binding, uniformly on top losses. Every candidate with
    q >= 0 is feasible, so the maximum over feasible candidates is the optimum."""
    L = -np.sort(-np.asarray(L, float), axis=-1)
    N = L.shape[-1]
    p = 1.0 / N
    r = np.asarray(rho, float)[..., None] * p if np.ndim(rho) else rho * p
    k = np.arange(1, N + 1, dtype=float)
    cs, cs2 = np.cumsum(L, axis=-1), np.cumsum(L * L, axis=-1)
    m = cs / k
    V = np.maximum(cs2 - k * m * m, 0.0)
    base = k * (1.0 / k - p) ** 2 + (N - k) * p * p              # squared distance of 'uniform on the top k'
    tol = 1e-12
    best = np.where(base <= r + tol, m, -np.inf)
    R = r - base
    with np.errstate(divide="ignore", invalid="ignore"):
        c = np.sqrt(np.where((R > 0) & (V > 1e-12 * (1.0 + m * m)), R / V, np.nan))
        qmin = 1.0 / k + c * (L - m)                             # weight of the k-th largest loss
        ok = np.isfinite(c) & (qmin >= -1e-12)
        best = np.maximum(best, np.where(ok, m + c * V, -np.inf))
    return best.max(axis=-1)


def dro_objective(S, window, rho):
    """Worst-case expected newsvendor loss of ordering S against the ambiguity set built on `window` (last axis)."""
    return chi2_worst_case(newsvendor_loss(np.asarray(S, float)[..., None], window), rho)


def dro_orders_window(windows: np.ndarray, rho: float, iters: int = 48) -> np.ndarray:
    """Golden-section search for the robust order of each row of `windows` (the worst-case loss is convex in S, and
    the minimizer lies within the range of the observations, clipped at 0)."""
    lo = np.maximum(windows.min(axis=-1), 0.0)
    hi = np.maximum(windows.max(axis=-1), 0.0)
    g = (np.sqrt(5.0) - 1.0) / 2.0
    a, b = lo.copy(), hi.copy()
    x1, x2 = b - g * (b - a), a + g * (b - a)
    f1, f2 = dro_objective(x1, windows, rho), dro_objective(x2, windows, rho)
    for _ in range(iters):
        left = f1 <= f2
        b = np.where(left, x2, b)
        a = np.where(left, a, x1)
        nx1, nx2 = b - g * (b - a), a + g * (b - a)
        x1, x2 = np.where(left, nx1, x2), np.where(left, x1, nx2)
        f_new = dro_objective(np.where(left, x1, x2), windows, rho)
        f1, f2 = np.where(left, f_new, f2), np.where(left, f1, f_new)
    return 0.5 * (a + b)


def saa_order_window(windows: np.ndarray) -> np.ndarray:
    """Empirical (SAA) newsvendor order: the ceil(0.8 N)-th smallest observation (the smallest minimizer of the
    average loss), clipped at 0."""
    N = windows.shape[-1]
    k = int(np.ceil(FRACTILE * N - 1e-12))
    return np.maximum(np.sort(windows, axis=-1)[..., k - 1], 0.0)


def window_orders(y: np.ndarray, N: int, solver, fallback: np.ndarray) -> np.ndarray:
    """Orders from the last N observations before each period (fewer at the start; the default rule's order until two
    observations exist)."""
    T = len(y)
    S = np.array(fallback, float)
    for t in range(2, min(N, T)):
        S[t] = solver(y[None, :t])[0]
    if T > N:
        from numpy.lib.stride_tricks import sliding_window_view
        W = sliding_window_view(y, N)[:T - N]                    # W[j] = y[j : j + N], used at period j + N
        S[N:] = solver(W)
    return S


# ================================================================================================ running the agents
@lru_cache(maxsize=256)
def _stream(env: TaskEnv, T: int):
    s = tasks._streams(env, T, env.seed)
    dec = tasks._decisions(env, T, env.seed)
    return s["state"], s["outcome"], s["obs"], dec["d"]


def orders(env: TaskEnv, family: str, cfg: Dict[str, float], T: int, grid_step: float = 1.0) -> np.ndarray:
    mu, d, y, default = _stream(env, T)
    if family == "rule_b":
        return default
    if family == "ewma":
        return tasks._decisions(replace(env, gain=float(cfg["gain"])), T, env.seed)["x"]
    if family == "saa":
        return window_orders(y, int(cfg["window"]), saa_order_window, default)
    if family == "dro":
        return window_orders(y, int(cfg["window"]), lambda W: dro_orders_window(W, float(cfg["rho"])), default)
    if family == "bocpd":
        return bocpd_orders(y, float(cfg["hazard"]), float(cfg["prior_sd"]), float(cfg["obs_sd"]))
    if family == "bayes_true":
        return bayes_true_orders(y, env.hazard, env.noise, env.obs_noise, grid_step)
    if family == "oracle":
        return np.maximum(mu + Z_FRAC * env.noise, 0.0)
    raise ValueError(family)


def run_agent(env: TaskEnv, family: str, cfg: Dict[str, float], T: int, burn: int, grid_step: float = 1.0):
    mu, d, y, _ = _stream(env, T)
    S = orders(env, family, cfg, T, grid_step)
    pay = inventory_payoff(S, d)[burn:]
    return dict(payoff=float(pay.mean()), mean_order=float(S[burn:].mean()),
                noise=env.noise, hazard=env.hazard, obs_noise=env.obs_noise)


