"""Run the trial-by-trial human-model study and write its results.

Usage:  python tools/run_human_learning.py [<output directory>] [--quick] [--power-reps N]

Writes, into docs/human_learning_results/ by default, one CSV per export (see
heiner_abm.human_learning.EXPORTS) plus spec.json with the frozen plan, its hash and the code digest.

EVERYTHING HERE IS SYNTHETIC. The participants are generated by the models being fitted, in the real
interactive market, following the allocation schedule. The results say whether this design could identify these
mechanisms if people behaved this way. They are not evidence that anybody does, and nothing in this output is a
finding about human behaviour.
"""
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from heiner_abm import human_learning as L          # noqa: E402

args = list(sys.argv[1:])
opts = {}
if "--quick" in args:
    args.remove("--quick")
    opts.update(recovery_n=12, model_recovery_n=4, power_sizes=(12, 24), power_reps=3)
if "--power-reps" in args:
    i = args.index("--power-reps")
    opts["power_reps"] = int(args[i + 1])
    del args[i:i + 2]

out = Path(args[0]) if args else ROOT / "docs" / "human_learning_results"
out.mkdir(parents=True, exist_ok=True)

plan = L.LearnPlan(**opts)
print(f"plan {plan.digest} (code {L.learning_code_digest()}): {len(plan.models)} models, "
      f"recovery n={plan.recovery_n}, power sizes {plan.power_sizes} x {plan.power_reps} reps", flush=True)

t0 = time.time()
last = [0.0]


def note(fraction: float, message: str) -> None:
    if fraction - last[0] >= 0.02 or fraction >= 1.0:
        last[0] = fraction
        print(f"  {fraction * 100:5.1f}%  {message}   [{(time.time() - t0) / 60:5.1f} min]", flush=True)


frames = L.run_study(plan, progress=note)
for name, df in frames.items():
    df.to_csv(out / f"{name}.csv", index=False)

(out / "spec.json").write_text(json.dumps({
    "plan_digest": plan.digest,
    "code_digest": L.learning_code_digest(),
    "plan": json.loads(plan.to_json()),
    "exports": L.EXPORTS,
    "claims": L.IDENTIFIABILITY_CLAIMS,
    "synthetic": True,
    "note": "Synthetic participants generated by the models under test. Not evidence about people.",
}, indent=1, default=str), encoding="utf-8")

print(f"\nelapsed {(time.time() - t0) / 60:.1f} min")
print("\n=== parameter recovery (correlation of estimate with truth) ===")
pr = frames["parameter_recovery"].pivot_table(index="parameter", columns="model", values="correlation")
print(pr.round(2).to_string())
print("\n=== model recovery (rows: generating, columns: selected) ===")
print(frames["model_recovery"].round(2).to_string(index=False))
print("\n=== identifiability ===")
print(frames["identifiability"][["claim", "value", "supported", "detail"]].to_string(index=False))
print("\n=== power ===")
print(frames["power"].to_string(index=False))
print(f"\nwrote {out}")
